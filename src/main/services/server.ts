import { promises as fs } from 'node:fs';
import { join } from 'node:path';
import { spawn, type ChildProcess } from 'node:child_process';
import { createInterface } from 'node:readline';
import type { LogLine } from '../../shared/types';
import { downloadVerified, fetchJson, type NetOptions } from './net';
import { fetchManifest, NET, type VersionJson } from './mojang';
import { backupWorld } from './worlds';

export type ServerType = 'vanilla' | 'paper' | 'fabric';
export const SERVER_TYPES: ServerType[] = ['vanilla', 'paper', 'fabric'];

export interface ServerProperties {
  port: number;
  motd: string;
  onlineMode: boolean;
  seed?: string;
}

/**
 * server.properties: RCON и query всегда выключены.
 * seed задаётся только при создании мира — при повторном запуске не меняем.
 */
export function renderServerProperties(p: ServerProperties): string {
  const lines = [
    '# Generated by VOXEL',
    `server-port=${p.port}`,
    `motd=${p.motd.replace(/[\r\n]/g, ' ')}`,
    `online-mode=${p.onlineMode ? 'true' : 'false'}`,
    'enable-rcon=false',
    'enable-query=false',
    'white-list=false',
    'enforce-whitelist=false',
  ];
  if (p.seed !== undefined) lines.push(`level-seed=${p.seed}`);
  return lines.join('\n') + '\n';
}

/** Не даём перезаписать level-seed у существующего мира: сохраняем строку из файла. */
export function mergeServerProperties(existing: string, incoming: string): string {
  const current = existing.match(/^level-seed=.*$/m);
  if (!current) return incoming;
  if (/^level-seed=/m.test(incoming)) return incoming.replace(/^level-seed=.*$/m, current[0]);
  return incoming + current[0] + '\n';
}

export const BACKUP_INTERVALS = { '30m': 30 * 60_000, '1h': 60 * 60_000, '24h': 24 * 3600_000 } as const;
export type BackupInterval = keyof typeof BACKUP_INTERVALS;
export const BACKUP_KEEP = 5;

/** Оставляет последние `keep` бэкапов (по времени изменения), остальные удаляет. */
export async function pruneBackups(dir: string, keep = BACKUP_KEEP): Promise<string[]> {
  let names: string[] = [];
  try {
    names = (await fs.readdir(dir)).filter((n) => n.endsWith('.zip'));
  } catch {
    return [];
  }
  const withTime = await Promise.all(
    names.map(async (n) => ({ n, t: (await fs.stat(join(dir, n))).mtimeMs })),
  );
  withTime.sort((a, b) => b.t - a.t);
  const removed: string[] = [];
  for (const { n } of withTime.slice(keep)) {
    await fs.unlink(join(dir, n));
    removed.push(n);
  }
  return removed;
}

export interface ServerJarInfo {
  url: string;
  sha1?: string;
  sha256?: string;
  size?: number;
  fileName: string;
}

/** Адрес серверного jar. Vanilla — из манифеста Mojang (SHA-1), Paper — API PaperMC (SHA-256). */
export async function resolveServerJar(type: ServerType, mc: string, signal?: AbortSignal): Promise<ServerJarInfo> {
  if (type === 'vanilla') {
    const entry = (await fetchManifest(signal)).find((v) => v.id === mc);
    if (!entry) throw new Error(`Версия ${mc} не найдена в манифесте`);
    const vj = await fetchJson<VersionJson>(entry.url, NET, signal);
    const srv = vj.downloads?.server;
    if (!srv) throw new Error(`У версии ${mc} нет серверного jar`);
    return { url: srv.url, sha1: srv.sha1, size: srv.size, fileName: 'server.jar' };
  }
  if (type === 'paper') {
    const net: NetOptions = { hosts: ['api.papermc.io'] };
    const builds = await fetchJson<{ builds: { build: number; downloads: { application: { name: string; sha256: string } } }[] }>(
      `https://api.papermc.io/v2/projects/paper/versions/${mc}/builds`, net, signal,
    );
    const last = builds.builds.at(-1);
    if (!last) throw new Error(`Нет сборок Paper для ${mc}`);
    const app = last.downloads.application;
    return {
      url: `https://api.papermc.io/v2/projects/paper/versions/${mc}/builds/${last.build}/downloads/${app.name}`,
      sha256: app.sha256,
      fileName: 'server.jar',
    };
  }
  // fabric: установщик → серверный jar для последней стабильной версии loader
  const net: NetOptions = { hosts: ['meta.fabricmc.net'] };
  const installers = await fetchJson<{ version: string; stable: boolean }[]>('https://meta.fabricmc.net/v2/versions/installer', net, signal);
  const installer = installers.find((i) => i.stable)?.version;
  const loaders = await fetchJson<{ loader: { version: string; stable: boolean } }[]>(
    `https://meta.fabricmc.net/v2/versions/loader/${mc}`, net, signal,
  );
  const loader = loaders.find((l) => l.loader.stable)?.loader.version;
  if (!installer || !loader) throw new Error(`Fabric недоступен для ${mc}`);
  return {
    url: `https://meta.fabricmc.net/v2/versions/loader/${mc}/${loader}/${installer}/server/jar`,
    fileName: 'server.jar',
  };
}

export async function installServerJar(type: ServerType, mc: string, dir: string, signal?: AbortSignal): Promise<void> {
  await fs.mkdir(dir, { recursive: true });
  const info = await resolveServerJar(type, mc, signal);
  const host = new URL(info.url).hostname;
  await downloadVerified(
    { url: info.url, path: join(dir, info.fileName), sha1: info.sha1, sha256: info.sha256, size: info.size },
    { hosts: [host] },
    signal,
  );
}

export interface ServerRuntime {
  child: ChildProcess;
  backupTimer: NodeJS.Timeout | null;
}

let running: ServerRuntime | null = null;

export function serverRunning(): boolean {
  return running !== null;
}

/** Запуск сервера. stdin используется как консоль. Автобэкапы мира — по интервалу, хранится 5. */
export function startServer(
  dir: string,
  javaExe: string,
  ramMb: number,
  backupEvery: BackupInterval | null,
  onLog: (l: LogLine) => void,
  onExit: (code: number | null) => void,
): void {
  if (running) throw new Error('Сервер уже запущен');
  const child = spawn(javaExe, [`-Xmx${ramMb}M`, '-jar', 'server.jar', 'nogui'], { cwd: dir, shell: false, windowsHide: true });
  const time = () => new Date().toLocaleTimeString('ru-RU');
  const emit = (text: string) => onLog({ level: /ERROR|WARN/.test(text) ? (/ERROR/.test(text) ? 'error' : 'warn') : 'java', text, time: time() });
  if (child.stdout) createInterface({ input: child.stdout }).on('line', emit);
  if (child.stderr) createInterface({ input: child.stderr }).on('line', emit);

  let backupBusy = false;
  const backupTimer = backupEvery
    ? setInterval(() => {
        if (backupBusy) return;
        backupBusy = true;
        void backupWorld(dir, join(dir, 'backups'), 'world')
          .then((f) => pruneBackups(join(dir, 'backups')).then(() => emit(`[VOXEL] Автобэкап: ${f}`)))
          .catch((e: Error) => emit(`[VOXEL] Автобэкап не выполнен: ${e.message}`))
          .finally(() => { backupBusy = false; });
      }, BACKUP_INTERVALS[backupEvery])
    : null;

  running = { child, backupTimer };
  child.on('exit', (code) => {
    if (backupTimer) clearInterval(backupTimer);
    running = null;
    onExit(code);
  });
  child.on('error', (e) => emit(`Не удалось запустить сервер: ${e.message}`));
}

export function sendServerCommand(cmd: string): boolean {
  if (!running?.child.stdin || cmd.includes('\n') || cmd.length > 512) return false;
  running.child.stdin.write(`${cmd}\n`);
  return true;
}

export function stopServer(): boolean {
  if (!running) return false;
  sendServerCommand('stop');
  return true;
}
